// Real-browser menu and local-record regressions. Requires Vite and a race server.
// node tools/menu-check.mjs [url] [screenshot directory]
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
const url = process.argv[2] ?? 'http://localhost:8000/';
const shots = process.argv[3];
if (shots) await mkdir(shots, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', args: ['--use-angle=metal', '--ignore-gpu-blocklist'] });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('request', (r) => { if (/identitytoolkit|securetoken|firestore/.test(r.url())) errors.push(r.url()); });
  await page.goto(url);
  await page.getByRole('button', { name: 'Single Player', exact: true }).waitFor();
  const fixture = '/@fs' + fileURLToPath(new URL('./records-fixture.mjs', import.meta.url));
  await page.evaluate(async (path) => (await import(path)).captureMenuStage(), fixture);
  await page.getByRole('button', { name: 'Single Player', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Battles', exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: /^View:/ }).count(), 0);
  const bounds = () => page.locator('.track-picker').boundingBox();
  const before = await bounds();
  await page.getByRole('button', { name: 'Sprints', exact: true }).click();
  assert.deepEqual(await bounds(), before);
  await page.getByRole('button', { name: 'Circuits', exact: true }).click();
  assert.deepEqual(await bounds(), before);
  assert.equal(await page.locator('.card .muted').count(), 0);
  if (shots) await page.screenshot({ path: `${shots}/tracks.png` });
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await page.locator('.lobby-drivers .crow').waitFor();
  assert.equal(await page.locator('.lobby-drivers .crow').count(), 1);
  assert.equal(await page.getByText('CPU DIFFICULTY', { exact: true }).count(), 0);
  const row = page.locator('.setting-row').filter({ hasText: 'LAPS' });
  const rowBounds = await row.boundingBox();
  const arrow = page.getByRole('button', { name: 'Increase laps' });
  await arrow.hover(); await page.mouse.down();
  assert.deepEqual(await row.boundingBox(), rowBounds);
  if (shots) await page.screenshot({ path: `${shots}/pressed-picker.png` });
  await page.mouse.up();
  assert.deepEqual(await row.boundingBox(), rowBounds);
  if (shots) await page.screenshot({ path: `${shots}/solo-ready.png` });
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await page.locator('.track-picker').waitFor();
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await page.getByRole('button', { name: 'Garage', exact: true }).click();
  await page.getByRole('button', { name: 'Paint 3', exact: true }).click();
  await page.waitForTimeout(350);
  assert.equal(await page.locator('.garage-preview').count(), 1);
  assert.equal(await page.locator('.paint-swatch img').count(), 3);
  if (shots) await page.screenshot({ path: `${shots}/garage.png` });
  await page.getByRole('button', { name: 'Select', exact: true }).click();
  await page.getByRole('button', { name: 'Garage', exact: true }).waitFor();
  await page.waitForTimeout(100);
  assert.deepEqual(await page.evaluate(async (path) => (await import(path)).menuStageState(), fixture), { same: true, car: 6 });
  console.log('- fixed track/picker geometry, solo setup, garage selection, persistent chase stage');
  const checks = await page.evaluate(async (path) => (await import(path)).runChecks(), fixture);
  checks.forEach((c) => console.log(`- ${c}`));
  await page.evaluate(async (path) => (await import(path)).garageLifecycleChecks(), fixture);
  console.log('- all 15 garage paints/models, repeated navigation and GPU resource disposal');
  await page.reload();
  await page.getByRole('button', { name: 'Single Player', exact: true }).waitFor();
  assert.equal(await page.evaluate(async (path) => (await import(path)).persistedTime(), fixture), 4);
  console.log('- PB survives a full reload');
  await page.evaluate(async (path) => (await import(path)).storageFailureCheck(), fixture);
  console.log('- blocked storage supports session-only PBs');
  await page.setViewportSize({ width: 844, height: 390 });
  await page.getByRole('button', { name: 'Single Player', exact: true }).click();
  await page.locator('.track-picker').waitFor();
  const phone = await bounds();
  assert(phone.x >= 0 && phone.x + phone.width <= 844 && phone.y >= 0 && phone.y + phone.height <= 390, 'phone track picker must fit');
  if (shots) await page.screenshot({ path: `${shots}/tracks-phone.png` });
  console.log('- landscape phone picker fits the viewport');
  if (shots) {
    await page.evaluate(async (path) => (await import(path)).prepareBlockShot(), fixture);
    await page.setViewportSize({ width: 720, height: 480 });
    await page.screenshot({ path: `${shots}/lucky-block-faces.png` });
  }
  assert.deepEqual(errors, []);
} finally { await browser.close(); }
