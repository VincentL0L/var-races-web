// Prepares the game's assets for the web: assets/ -> web/public/gen/, plus web/src/gen/assets.ts,
// which maps every asset to its URL. Each URL carries a hash of the file, so browsers can cache
// them for good (see firebase.json) and still get a new version the moment one changes.
//
//  - pictures become WebP (lossless for pixel art, which is most of them, and for each map's
//    heights.png, whose exact pixel values are building heights)
//  - fonts and sounds are copied as they are
// Run: npm run assets
import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, rm, writeFile, copyFile } from 'node:fs/promises';
import { dirname, join, relative, extname } from 'node:path';
import sharp from 'sharp';

const root = new URL('..', import.meta.url).pathname;
const src = join(root, 'assets');
const out = join(root, 'web/public/gen');
const manifest = {};

/** pictures that aren't pixel art, where lossy compression is invisible */
const LOSSY = new Set(['maps/classic/background.png']);

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(path);
    else yield path;
  }
}

async function emit(name, data) {
  const path = join(out, name);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, data);
  const hash = createHash('sha256').update(data).digest('hex').slice(0, 10);
  manifest[name] = `/gen/${name}?v=${hash}`;
}

async function convert(file) {
  const name = relative(src, file);
  const ext = extname(name);
  const base = name.slice(0, -ext.length);
  if (name.endsWith('road_mask.png')) return; // the simulation has its own packed copy
  if (name === 'ui/grass.png') {
    // only this corner of the grass picture is ever drawn
    return emit('ui/grass.webp', await sharp(file).extract({ left: 0, top: 0, width: 512, height: 512 }).webp({ lossless: true }).toBuffer());
  }
  if (ext === '.png') {
    const webp = LOSSY.has(name) || name.endsWith('preview.png') ? { quality: 86 } : { lossless: true };
    return emit(`${base}.webp`, await sharp(file).webp(webp).toBuffer());
  }
  if (['.wav', '.mp3', '.woff2'].includes(ext)) {
    return emit(name, await readFile(file));
  }
}

await rm(out, { recursive: true, force: true });
const files = [];
for await (const file of walk(src)) files.push(file);
await Promise.all(files.map(convert));

const names = Object.keys(manifest).sort();
const ts = `// Generated by tools/web-assets.mjs. Do not edit.
const urls: Record<string, string> = {
${names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(manifest[n])},`).join('\n')}
};

/** the URL of a generated asset, by its path under assets/ (pictures as .webp) */
export function asset(name: string): string {
  const url = urls[name];
  if (!url) throw new Error(\`no asset \${name}\`);
  return url;
}

export function hasAsset(name: string): boolean {
  return name in urls;
}
`;
await mkdir(join(root, 'web/src/gen'), { recursive: true });
await writeFile(join(root, 'web/src/gen/assets.ts'), ts);
const total = (await Promise.all(names.map((n) => readFile(join(out, n))))).reduce((s, b) => s + b.length, 0);
console.log(`assets: ${names.length} files, ${(total / 1024).toFixed(0)} KB`);
